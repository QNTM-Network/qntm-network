/**
 * measure-the-divergence — HOW OFTEN DOES THE BROWSER'S PREDICTION DIFFER FROM WHAT THE ENGINE
 * ACTUALLY RETURNS? Per resolver, not one aggregate. `docs/implementation-artifacts/
 * design-the-two-rules.md` §5 is the document this number feeds.
 *
 *   node scripts/measure-the-divergence.mjs
 *
 * ── WHY THIS EXISTS, AND THE ONE RULE IT MUST NEVER BREAK ──
 *
 * The operator's own words: the perception rule — no spinner, no "saving", the browser is
 * authoritative until the engine disagrees — is only as good as the resolver gap it is betting on
 * being small. This script measures that gap. It is a BUILD-TIME REPORT, never operator-visible:
 * it imports `dist/present.js` the same way every test in `tests/` already does, it writes nothing
 * back into the app, it is reachable from no HTML page, and `npm run build` does not touch it. The
 * one requirement that cannot bend — not now, not behind a flag, not in a corner — is that this
 * number is never shown to the operator. It is shown to US, on a terminal, when we ask for it.
 *
 * ── WHERE THE GROUND TRUTH COMES FROM, AND WHY IT IS NOT INVENTED ──
 *
 * Every comparison below replays a fixture ALREADY CHECKED INTO THIS REPO, generated by calling
 * the engine's own Python — `matches_pattern`, `ResolutionCascade`/`resolve_registration_keys`,
 * `resolve_logical_day`/`resolve_week_end` — over the operator's real config and (for membership) a
 * read-only copy of his real graph. Nothing here re-derives a truth side by hand, and nothing here
 * re-runs those generators: `--state-db` must be a copy of the operator's live database, this
 * script does not open one, and per the standing rule no cycle runs and nothing is read from
 * `~/qntm` or `~/.qntm-md`. The fixtures are the "honest inputs" the brief asks for; this script
 * only replays them through the browser's real, shipped resolver code and counts where the two
 * disagree — the same shape `tests/qualification-agreement.test.mjs` and
 * `tests/resolution-agreement.test.mjs` already use to prove agreement, extended here to REPORT A
 * RATE rather than assert a binary pass.
 *
 * ── FOUR AXES, NOT ONE NUMBER ──
 *
 * `measureMembership`, `measureOrdering`, `measureRules` each return a real, computed divergence
 * count over real fixture data. `measurePromotion` returns `{ measured: false, reason }` — no
 * fixture in this repo carries engine ground truth for a ONE-HOP graph-dependent decision;
 * `qualification-agreement.py`'s own header explains why its method cannot produce one
 * (`GRAPH_DEPENDENT`, excluded by construction, not by oversight). Reporting a number for that axis
 * would mean inventing an oracle this repo does not have. See `design-the-two-rules.md` §5.4 for
 * what would need to exist before it could be measured honestly.
 */

import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  matchesQualifier,
  readQualificationDeclaration,
  readConfigResolutionDeclaration,
  todayFor,
} from "../dist/present.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..");
const read = (path) => JSON.parse(readFileSync(resolve(REPO, path), "utf8"));

// ══════════════════════════════════════════════════════════════════════════════════════════════
// MEMBERSHIP — does `matchesQualifier` agree with `qntm_graph.patterns.engine.matches_pattern`
// over every field triple the real graph holds AND every triple a line being typed can reach?
// ══════════════════════════════════════════════════════════════════════════════════════════════

export function measureMembership() {
  const truth = read("tests/fixtures/qualification-agreement.json");
  const served = read("presentation.json");
  const language = readQualificationDeclaration(served).qualification;

  const appAnswer = (fields) =>
    truth.patterns.filter((name) => matchesQualifier(fields, language.predicates[name])).sort();

  let cells = 0;
  let mismatches = 0;
  const disagreements = [];

  const check = (fields, matchIndex, source) => {
    cells += 1;
    const expected = [...truth.matchSets[matchIndex]].sort();
    const actual = appAnswer(fields);
    if (expected.length !== actual.length || expected.some((p, i) => p !== actual[i])) {
      mismatches += 1;
      if (disagreements.length < 10) {
        disagreements.push({ source, fields, expected, actual });
      }
    }
  };

  for (const row of truth.rows) {
    check(row.fields, row.matches, "real-graph-row");
  }
  const { node_type: types, domain: domains, status: statuses } = truth.probeAxes;
  let i = 0;
  for (const node_type of types) {
    for (const domain of domains) {
      for (const status of statuses) {
        check({ node_type, domain, status }, truth.probeCells[i], "typeable-probe");
        i += 1;
      }
    }
  }

  return {
    axis: "membership",
    measured: true,
    groundTruth: "qntm_graph.patterns.engine.matches_pattern, real graph + every typeable triple",
    cellsChecked: cells,
    mismatches,
    divergenceRate: mismatches / cells,
    scopeNote:
      "covers the PREDICATE only (given a field set, does the app reach the engine's verdict). " +
      "Does NOT cover FIELD RESOLUTION (does a given LINE resolve to that field set) — that half " +
      "is checked against the declared registration cascade in tests/present-membership.test.mjs, " +
      "never against a running engine, because minting a node to check it would mean running a " +
      "cycle. See qualification-agreement.test.mjs's own header for the identical caveat.",
    disagreements,
  };
}

// ══════════════════════════════════════════════════════════════════════════════════════════════
// ORDERING — does the browser's published default-ordering tuple and priority-rank table agree
// with a LIVE import of the engine's own `_DEFAULT_ORDERING`/`_PRIORITY_RANK`?
// ══════════════════════════════════════════════════════════════════════════════════════════════

export function measureOrdering() {
  const truth = read("tests/fixtures/resolution-agreement.json");
  const served = read("presentation.json");
  const resolution = readConfigResolutionDeclaration(served).resolution;

  let cells = 0;
  let mismatches = 0;
  const disagreements = [];

  // The tuple itself: field-for-field, direction-for-direction, in the engine's own order.
  const tupleLen = Math.max(resolution.defaultOrdering.length, truth.defaultOrdering.length);
  for (let i = 0; i < tupleLen; i += 1) {
    cells += 1;
    const appKey = resolution.defaultOrdering[i];
    const engineKey = truth.defaultOrdering[i];
    const agree =
      appKey !== undefined &&
      engineKey !== undefined &&
      appKey.field === engineKey.field &&
      appKey.direction === engineKey.direction;
    if (!agree) {
      mismatches += 1;
      disagreements.push({ source: "defaultOrdering", index: i, expected: engineKey, actual: appKey });
    }
  }

  // The rank table: every name, every number.
  const names = new Set([...Object.keys(resolution.priorityRank), ...Object.keys(truth.priorityRank)]);
  for (const name of names) {
    cells += 1;
    if (resolution.priorityRank[name] !== truth.priorityRank[name]) {
      mismatches += 1;
      disagreements.push({
        source: "priorityRank",
        name,
        expected: truth.priorityRank[name],
        actual: resolution.priorityRank[name],
      });
    }
  }

  return {
    axis: "ordering",
    measured: true,
    groundTruth:
      "qntm_md.render.section_builder._DEFAULT_ORDERING / _PRIORITY_RANK, live-imported by " +
      "scripts/resolution-agreement.py",
    cellsChecked: cells,
    mismatches,
    divergenceRate: mismatches / cells,
    scopeNote:
      "covers the DEFAULT-PATH TIE-BREAK CONSTANTS `defaultOrderingFor` uses for every section " +
      "with no declared `ordering:`/`ordering_mode:` (171 of the operator's sections, per " +
      "ordering.ts's own header). Does NOT cover a live per-commit placement outcome against a " +
      "running cycle, and does NOT cover DECLARED-ordering sections (`orderingFor`'s own path), " +
      "for which no engine-side fixture exists in this repo — see design-the-two-rules.md §5.4.",
    disagreements,
  };
}

// ══════════════════════════════════════════════════════════════════════════════════════════════
// RULES — the one sub-question this repo can check against the engine without a graph: does
// `todayFor` (the day-boundary dependency of `stamp-created-at-on-task`) agree with
// `resolve_logical_day`/`resolve_week_end`?
// ══════════════════════════════════════════════════════════════════════════════════════════════

export function measureRules() {
  const truth = read("tests/fixtures/day-boundary-agreement.json");

  let cells = 0;
  let mismatches = 0;
  const disagreements = [];

  for (const c of truth.cases) {
    cells += 1;
    const nowUtcMs = Date.parse(c.nowUtcIso);
    const boundary = {
      timezone: c.boundary.timezone,
      dayStartHour: c.boundary.dayStartHour,
      weekStartsOn: c.boundary.weekStartsOn,
    };
    const reading = todayFor(nowUtcMs, boundary);
    const agree =
      reading.kind === "answer" &&
      reading.answer.logicalDate === c.logicalDate &&
      reading.answer.weekEnd === c.weekEnd;
    if (!agree) {
      mismatches += 1;
      disagreements.push({ case: c, actual: reading });
    }
  }

  return {
    axis: "rules",
    measured: true,
    groundTruth:
      "qntm_md.substrate_wiring.day_boundary.resolve_logical_day / resolve_week_end, live-called " +
      "by scripts/day-boundary-agreement.py",
    cellsChecked: cells,
    mismatches,
    divergenceRate: mismatches / cells,
    scopeNote:
      "covers ONE rule's dependency (today.ts, which stamp-created-at-on-task reads) across " +
      "14 real-config boundary cases (both DST regimes, the rollover instant, two config " +
      "sensitivities). Does NOT cover the other rules `rules.ts`'s `applyRules` evaluates — those " +
      "are checked at CONFIG-COMPILE time (validate_rules cross-referencing patterns, the same " +
      "mechanism design-gate-two.md §2.1 describes) never against a per-commit engine execution, " +
      "because no fixture in this repo carries one. See design-the-two-rules.md §5.4.",
    disagreements,
  };
}

// ══════════════════════════════════════════════════════════════════════════════════════════════
// PARENT PROMOTION — NOT MEASURABLE from anything checked into this repo today, and said so rather
// than guessed at.
// ══════════════════════════════════════════════════════════════════════════════════════════════

export function measurePromotion() {
  return {
    axis: "parent-promotion",
    measured: false,
    reason:
      "graphmatch.ts's whole reason to exist is the ONE-HOP case qualification-agreement.py's own " +
      "header excludes by name (GRAPH_DEPENDENT) — its method (key a fixture on one node's own " +
      "triple, prove one triple gets one answer) is invalid by construction for a predicate whose " +
      "answer depends on a NEIGHBOUR's fields, which is exactly what a parent-promotion decision " +
      "is. No other fixture in this repo carries per-node one-hop engine verdicts against the real " +
      "graph. Producing one would mean writing a NEW engine-side generator (Python, against a " +
      "read-only copy of state.db, the same posture qualification-agreement.py already takes) — " +
      "new engine-side tooling, not a replay of what already exists, and therefore not built by " +
      "this script. Filed as its own backlog row rather than guessed at.",
  };
}

function report() {
  const results = [measureMembership(), measureOrdering(), measureRules(), measurePromotion()];
  for (const r of results) {
    console.log(`\n── ${r.axis} ──`);
    if (!r.measured) {
      console.log(`  NOT MEASURABLE: ${r.reason}`);
      continue;
    }
    const pct = (r.divergenceRate * 100).toFixed(4);
    console.log(`  ground truth: ${r.groundTruth}`);
    console.log(`  cells checked: ${r.cellsChecked}`);
    console.log(`  mismatches: ${r.mismatches}`);
    console.log(`  divergence rate: ${pct}% (${r.mismatches}/${r.cellsChecked})`);
    console.log(`  scope: ${r.scopeNote}`);
    if (r.disagreements.length > 0) {
      console.log(`  first disagreements:`, JSON.stringify(r.disagreements.slice(0, 5), null, 2));
    }
  }
  return results;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  report();
}
